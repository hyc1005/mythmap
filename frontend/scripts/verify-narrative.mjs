async function assertFullscreenLayout(page, label) {
  const layout = await page.evaluate(() => {
    const rect = element => { const r = element.getBoundingClientRect(); return { x:r.x, y:r.y, width:r.width, height:r.height }; };
    const collect = selector => Array.from(document.querySelectorAll(selector)).filter(e => e.getBoundingClientRect().width && getComputedStyle(e).visibility !== "hidden").map(rect);
    return { top:rect(document.querySelector(".fullscreen-toolbar")), map:rect(document.querySelector(".map-surface")), bottom:rect(document.querySelector(".fullscreen-dock")), width:innerWidth, height:innerHeight, controls:collect(".fullscreen-chapter-nav > button, .fullscreen-chapter-nav > span, .fullscreen-toolbar .myth-layer-switches label, .fullscreen-toolbar .map-animation-choice, .fullscreen-toolbar .map-tools, .fullscreen-toolbar .map-fullscreen, .fullscreen-dock .journey-actions > button, .fullscreen-dock .pangu-player-controls > button") };
  });
  assert.ok(layout.top.y + layout.top.height <= layout.map.y + 1 && layout.map.y + layout.map.height <= layout.bottom.y + 1, label + ": control bands stay outside the canvas");
  assert.ok(layout.map.height >= 100 && layout.bottom.y + layout.bottom.height <= layout.height + 1, label + ": canvas and bands fit the viewport");
  for (let i=0;i<layout.controls.length;i++) {
    const a=layout.controls[i]; assert.ok(a.x >= -1 && a.y >= -1 && a.x+a.width <= layout.width+1 && a.y+a.height <= layout.height+1, label + ": control visible");
    for(let j=i+1;j<layout.controls.length;j++){const b=layout.controls[j]; assert.ok(a.x+a.width<=b.x+1 || b.x+b.width<=a.x+1 || a.y+a.height<=b.y+1 || b.y+b.height<=a.y+1, label + ": controls do not overlap");}
  }
}

async function assertDetailDrawer(page, label) {
  const drawer = page.getByRole('dialog');
  await drawer.waitFor();
  await page.clock.runFor(300);
  assert.equal(await drawer.locator('.drawer-fullscreen').count(), 0, label + ': no map fullscreen entry');
  const close = drawer.getByRole('button', { name: '关闭', exact: true });
  const actions = await drawer.locator('.drawer-actions').boundingBox();
  for (const selector of ['.intro-overline', 'h2']) {
    const rect = await drawer.locator(selector).boundingBox();
    assert.ok(rect.y >= actions.y + actions.height, label + ': heading clears actions');
  }
  const controls = drawer.locator('button:not(:disabled), a[href]');
  await controls.first().focus();
  await page.keyboard.press('Shift+Tab');
  assert.equal(await controls.last().evaluate(element => element === document.activeElement), true, label + ': reverse focus wraps');
  await page.keyboard.press('Tab');
  assert.equal(await close.evaluate(element => element === document.activeElement), true, label + ': focus returns to close');
  await drawer.evaluate(element => { element.scrollTop = element.scrollHeight; });
  await page.clock.runFor(100);
  assert.equal(await close.evaluate(element => {
    const rect = element.getBoundingClientRect();
    return rect.top >= 0 && rect.bottom <= innerHeight && document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2) === element;
  }), true, label + ': close remains visible and clickable after scrolling');
}

