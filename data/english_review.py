COMMENTARY = {}
CENTRAL_REVIEW_QUOTE_IDS = set()
for number, review in (("01", FIRST_CENTRAL_RANGE), ("02", CENTRAL_RANGE_02), ("03", CENTRAL_RANGE_03), ("04", CENTRAL_RANGE_04), ("05", CENTRAL_RANGE_05), ("06", CENTRAL_RANGE_06)):
    for slug, (source, quote, commentary, note) in review.items():
        card_kind = "rite" if slug == "summary" else "place"
        for prefix in ("passage", card_kind):
            entry_id = f"{prefix}-zhongshan-r{number}-{slug}"
            if quote is not None:
                QUOTES[entry_id] = (source, quote)
                CENTRAL_REVIEW_QUOTE_IDS.add(entry_id)
            if note is not None:
                COMMENTARY[entry_id] = (commentary, note)


def apply_quote_review(world, english):
    entries = {entry["id"]: entry for group in world.values() if isinstance(group, list)
               for entry in group if isinstance(entry, dict) and "id" in entry}
    for entry_id, (source, translation) in QUOTES.items():
        assert entries[entry_id]["quote"] == source, f"English review source changed: {entry_id}"
        previous = english[entry_id]["quote"]
        description = english[entry_id].get("description", "")
        if entry_id in CENTRAL_REVIEW_QUOTE_IDS and description.startswith(previous):
            english[entry_id]["description"] = translation + description[len(previous):]
        english[entry_id]["quote"] = translation
    for entry_id, (source, translation) in COMMENTARY.items():
        assert entries[entry_id]["commentary_quote"] == source, f"English commentary source changed: {entry_id}"
        english[entry_id]["commentary_quote"] = translation


